# matrix-graph build: bundle core.js + renderer.js + src-plugin.js into main.js
# Obsidian only loads main.js and cannot require sibling files, so bundling is required.
# Usage: powershell -ExecutionPolicy Bypass -File build.ps1

$ErrorActionPreference = 'Stop'
$dir = $PSScriptRoot

$core = [System.IO.File]::ReadAllText((Join-Path $dir 'core.js'), [System.Text.Encoding]::UTF8)
$rend = [System.IO.File]::ReadAllText((Join-Path $dir 'renderer.js'), [System.Text.Encoding]::UTF8)
$plug = [System.IO.File]::ReadAllText((Join-Path $dir 'src-plugin.js'), [System.Text.Encoding]::UTF8)
$sett = [System.IO.File]::ReadAllText((Join-Path $dir 'src-settings.js'), [System.Text.Encoding]::UTF8)
$mtx = [System.IO.File]::ReadAllText((Join-Path $dir 'src-matrix.js'), [System.Text.Encoding]::UTF8)

$header = @(
  '/* matrix-graph - single-file build generated by build.ps1. Do not edit by hand. */'
  "const { Plugin, ItemView, MarkdownRenderChild, TFile, Notice, PluginSettingTab, Setting, Menu, Platform, normalizePath } = require('obsidian');"
  ''
  'const MatrixCore = (function () {'
  '  var module = { exports: {} };'
  '  var exports = module.exports;'
) -join "`n"

$mid = @(
  '  return module.exports;'
  '})();'
  ''
  'const MatrixRenderer = (function () {'
  '  var module = { exports: {} };'
  '  var exports = module.exports;'
) -join "`n"

$body = @(
  '  return module.exports;'
  '})();'
  ''
) -join "`n"

$out = $header + "`n" + $core + "`n" + $mid + "`n" + $rend + "`n" + $body + $plug + "`n" + $sett + "`n" + $mtx
[System.IO.File]::WriteAllText((Join-Path $dir 'main.js'), $out, (New-Object System.Text.UTF8Encoding($false)))

node --check (Join-Path $dir 'main.js')
if ($LASTEXITCODE -eq 0) {
  $kb = [math]::Round((Get-Item (Join-Path $dir 'main.js')).Length / 1KB, 1)
  "main.js built: $kb KB, syntax OK"
} else {
  throw 'main.js syntax check failed'
}
